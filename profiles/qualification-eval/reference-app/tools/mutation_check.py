def run_suite():
    return subprocess.run(
        [sys.executable, "-B", "-m", "unittest", "discover", "-s", "tests", "-t", "."],
        cwd=ROOT, capture_output=True, text=True, check=False,
    )


def main():
    if run_suite().returncode != 0:
        print("baseline suite must pass before mutating")
        return 2
    survivors = 0
    for rel, old, new, label in MUTANTS:
        path = ROOT / rel
        original = path.read_text(encoding="utf-8")
        pairs = list(zip(old, new, strict=True)) if isinstance(old, tuple) else [(old, new)]
        if any(o not in original for o, _ in pairs):
            print(f"STALE    {label} (pattern not found in {rel})")
            survivors += 1
            continue
        mutated = original
        for o, n in pairs:
            mutated = mutated.replace(o, n, 1)
        path.write_text(mutated, encoding="utf-8")
        try:
            caught = run_suite().returncode != 0
        finally:
            path.write_text(original, encoding="utf-8")
        survivors += not caught
        print(("CAUGHT   " if caught else "SURVIVED ") + label)
    print(f"{len(MUTANTS) - survivors}/{len(MUTANTS)} mutants caught")
    return 1 if survivors else 0


if __name__ == "__main__":
    sys.exit(main())
